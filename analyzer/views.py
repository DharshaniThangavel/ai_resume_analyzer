from django.shortcuts import render, redirect, get_object_or_404
from django.contrib.auth.decorators import login_required  # <--- Import login_required
from .forms import ResumeUploadForm
from .models import Resume, JobDescription, AnalysisReport
from .utils.parser import extract_text_from_file
from .utils.matcher import calculate_semantic_similarity
from .utils.skills import analyze_skills
from .utils.auditor import audit_bullet_points

@login_required  # Protect route
def upload_resume(request):
    if request.method == 'POST':
        form = ResumeUploadForm(request.POST, request.FILES)
        if form.is_valid():
            # Save resume and assign logged-in user
            resume = form.save(commit=False)
            resume.user = request.user
            resume.save()

            jd_text = form.cleaned_data['job_description_text']
            job_desc = JobDescription.objects.create(
                description_text=jd_text,
                title="Target Job Description"
            )

            # Extract text & save
            file_path = resume.file.path
            resume_text = extract_text_from_file(file_path)
            resume.raw_text = resume_text
            resume.save()

            # AI Analysis Engine Calls
            semantic_score = calculate_semantic_similarity(resume_text, jd_text)
            matched, missing = analyze_skills(resume_text, jd_text)
            
            total_skills = len(matched) + len(missing)
            skill_match_score = round((len(matched) / total_skills) * 100, 2) if total_skills > 0 else 50.0

            bullet_feedback = audit_bullet_points(resume_text)
            overall_score = round((semantic_score * 0.6) + (skill_match_score * 0.4), 2)

            # Save report
            report = AnalysisReport.objects.create(
                resume=resume,
                job_description=job_desc,
                overall_score=overall_score,
                semantic_score=semantic_score,
                skill_match_score=skill_match_score,
                matched_skills=", ".join(matched),
                missing_skills=", ".join(missing),
                bullet_suggestions=bullet_feedback
            )

            return redirect('view_report', report_id=report.id)
    else:
        form = ResumeUploadForm()

    return render(request, 'analyzer/upload.html', {'form': form})


@login_required  # Protect route
def view_report(request, report_id):
    # Ensure users can only view their own reports
    report = get_object_or_404(AnalysisReport, id=report_id, resume__user=request.user)
    
    matched_list = [s.strip() for s in report.matched_skills.split(',')] if report.matched_skills else []
    missing_list = [s.strip() for s in report.missing_skills.split(',')] if report.missing_skills else []

    context = {
        'report': report,
        'matched_skills': matched_list,
        'missing_skills': missing_list,
        'bullet_suggestions': report.bullet_suggestions,
    }
    return render(request, 'analyzer/results.html', context)

@login_required
def history_view(request):
    """
    Displays all past analysis reports generated by the logged-in user.
    """
    reports = AnalysisReport.objects.filter(resume__user=request.user).order_by('-created_at')
    return render(request, 'analyzer/history.html', {'reports': reports})